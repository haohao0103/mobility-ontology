"""P4-1 OSDK-lite：从本体 JSON 生成 TypeScript + Python 类型化客户端。

对标 Palantir OSDK 的核心价值主张：类型从本体生成，本体演进 -> 客户端重新生成即同步，
应用编译期就能发现 schema 漂移。

用法：
    python tools/gen_osdk.py [--out generated/osdk]

生成产物：
    typescript.ts      所有类的 TS interface + 带类型的 OntologyClient
    python_client.py   所有类的 dataclass + OntologyClient
    openapi.json       OpenAPI 3.1 规范（任何语言可再生成）
"""
from __future__ import annotations

import argparse
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

from enhancements.registry import ExtensionRegistry  # noqa: E402
from freight.semantic import SemanticLayer  # noqa: E402

TS_TYPE = {"string": "string", "integer": "number", "number": "number", "boolean": "boolean"}
PY_TYPE = {"string": "str", "integer": "int", "number": "float", "boolean": "bool"}


def _pascal(name: str) -> str:
    return "".join(p[:1].upper() + p[1:] for p in name.split("_"))


def _ts_prop_type(ext, prop: str) -> str:
    pt = ext.property_types.get(prop)
    return TS_TYPE.get(pt.get("value_type", "string"), "string") if pt else "string"


def _derived_entries(sem: SemanticLayer) -> list[tuple[str, dict]]:
    """派生对象类型清单（本体声明，与实体类同等待遇进 codegen）。"""
    return [(d["id"], d) for d in sem.raw.get("derived_types", [])]


def _generate_ts_builders(sem: SemanticLayer, ext: ExtensionRegistry) -> list[str]:
    """E4：组合式查询的类型化构建器（对标 OSDK 编译期检查）。"""
    lines = [
        "// ---- 组合式 Object Set 查询构建器（E4）----",
        "export interface WhereOps<T> {",
        "  $eq?: T; $neq?: T; $gt?: T; $gte?: T; $lt?: T; $lte?: T;",
        "  $in?: T[]; $nin?: T[]; $contains?: string; $startswith?: string;",
        "  $endswith?: string; $exists?: boolean;",
        "}",
        "export interface QueryExtras {",
        "  set?: object;",
        "  orderBy?: Array<{ prop: string; dir?: 'asc' | 'desc' }>;",
        "  aggregate?: object;",
        "  page?: { limit?: number; offset?: number };",
        "}",
        "export interface ObjectSetQuery {",
        "  set: object;",
        "  where?: object;",
        "  orderBy?: Array<{ prop: string; dir?: 'asc' | 'desc' }>;",
        "  aggregate?: object;",
        "  page?: { limit?: number; offset?: number };",
        "}",
        "export function query<Q extends ObjectSetQuery>(q: Q): Q { return q; }",
        "",
    ]
    for cid, cls in sem.classes.items():
        name = _pascal(cid)
        lines.append(f"export interface {name}Filters {{")
        for prop in cls.get("properties", []):
            ts = _ts_prop_type(ext, prop)
            lines.append(f"  {prop}?: WhereOps<{ts}>;")
        lines.append("}")
        lines.append(
            f"export function {cid[0].lower() + cid[1:]}Query("
            f"where: {name}Filters, extras?: QueryExtras): ObjectSetQuery {{"
        )
        lines.append(f"  return {{ set: {{ from: '{cid}' }}, where, ...extras }};")
        lines.append("}")
        lines.append("")
    for did, dt in _derived_entries(sem):
        name = _pascal(did)
        lines.append(f"// 派生类型 {did}（{dt.get('label', did)}）：derivation 视图")
        lines.append(f"export interface {name}Filters {{")
        for prop in dt.get("properties", []):
            ts = _ts_prop_type(ext, prop)
            lines.append(f"  {prop}?: WhereOps<{ts}>;")
        lines.append("}")
        lines.append(
            f"export function {did[0].lower() + did[1:]}Query("
            f"where: {name}Filters, extras?: QueryExtras): ObjectSetQuery {{"
        )
        lines.append(f"  return {{ set: {{ from: '{did}' }}, where, ...extras }};")
        lines.append("}")
        lines.append("")
    return lines


def generate_typescript(sem: SemanticLayer, ext: ExtensionRegistry) -> str:
    lines = [
        "/** AUTO-GENERATED by tools/gen_osdk.py — OSDK-lite client.",
        " *  本体变更后重新生成：python tools/gen_osdk.py",
        " */",
        "",
        "export interface OntologyObject {",
        "  object_id: string;",
        "  type: string;",
        "}",
        "",
    ]
    for cid, cls in sem.classes.items():
        name = _pascal(cid)
        lines.append(f"export interface {name} extends OntologyObject {{")
        lines.append(f"  type: '{cid}';")
        for prop in cls.get("properties", []):
            pt = ext.property_types.get(prop)
            ts = TS_TYPE.get(pt.get("value_type", "string"), "string") if pt else "string"
            opt = "?" if not (pt and pt.get("primary_key")) else ""
            lines.append(f"  {prop}{opt}: {ts} | null;")
        lines.append("}")
        lines.append("")
    # 派生对象类型：与实体类同等待遇生成类型化接口（OSDK 侧一等公民）
    for did, dt in _derived_entries(sem):
        name = _pascal(did)
        lines.append(f"/** 派生类型：{dt.get('label', did)}（derivation 视图） */")
        lines.append(f"export interface {name} extends OntologyObject {{")
        lines.append(f"  type: '{did}';")
        for prop in dt.get("properties", []):
            pt = ext.property_types.get(prop)
            ts = TS_TYPE.get(pt.get("value_type", "string"), "string") if pt else "string"
            lines.append(f"  {prop}?: {ts} | null;")
        lines.append("}")
        lines.append("")
    lines.extend(_generate_ts_builders(sem, ext))
    lines.append("export class OntologyClient {")
    lines.append("  constructor(private baseUrl: string) {}")
    lines.append("")
    lines.append("  async fetchObjects(type: string, params?: {q?: string; limit?: number})")
    lines.append("      : Promise<{visible: number; objects: unknown[]}> {")
    lines.append("    const u = new URL(`${this.baseUrl}/enh/objects`);")
    lines.append("    u.searchParams.set('type', type);")
    lines.append("    if (params?.q) u.searchParams.set('q', params.q);")
    lines.append("    if (params?.limit) u.searchParams.set('limit', String(params.limit));")
    lines.append("    return (await fetch(u.toString())).json();")
    lines.append("  }")
    lines.append("")
    lines.append("  async callFunction<T>(functionId: string, args: Record<string, unknown>)")
    lines.append("      : Promise<T> {")
    lines.append("    const r = await fetch(`${this.baseUrl}/enh/functions/${functionId}/call`, {")
    lines.append("      method: 'POST', headers: {'content-type': 'application/json'},")
    lines.append("      body: JSON.stringify({args}),")
    lines.append("    });")
    lines.append("    if (!r.ok) throw new Error(await r.text());")
    lines.append("    return r.json();")
    lines.append("  }")
    lines.append("}")
    return "\n".join(lines) + "\n"


def generate_python(sem: SemanticLayer, ext: ExtensionRegistry) -> str:
    lines = [
        '"""AUTO-GENERATED by tools/gen_osdk.py — OSDK-lite Python client."""',
        "from __future__ import annotations",
        "",
        "import json",
        "from dataclasses import dataclass, field",
        "from typing import Any",
        "import urllib.request",
        "",
        "",
    ]
    for cid, cls in sem.classes.items():
        name = _pascal(cid)
        lines.append("@dataclass")
        lines.append(f"class {name}:")
        lines.append("    object_id: str")
        lines.append(f"    type: str = '{cid}'")
        for prop in cls.get("properties", []):
            if prop == cls.get("key"):
                continue
            pt = ext.property_types.get(prop)
            py = PY_TYPE.get(pt.get("value_type", "string"), "str") if pt else "str"
            lines.append(f"    {prop}: {py} | None = None")
        lines.append("")
    # 派生类型 dataclass（object_id/type 基础字段 + 派生声明属性）
    for did, dt in _derived_entries(sem):
        name = _pascal(did)
        lines.append("@dataclass")
        lines.append(f"class {name}:")
        lines.append("    object_id: str")
        lines.append(f"    type: str = '{did}'")
        for prop in dt.get("properties", []):
            pt = ext.property_types.get(prop)
            py = PY_TYPE.get(pt.get("value_type", "string"), "str") if pt else "str"
            lines.append(f"    {prop}: {py} | None = None")
        lines.append("")
    # E4：组合式查询构建器（TypedDict 类型化过滤 + 查询工厂）
    lines += [
        "from typing import TypedDict, Any, Optional",
        "",
        "",
        "class QueryExtras(TypedDict, total=False):",
        "    set: dict",
        "    orderBy: list",
        "    aggregate: dict",
        "    page: dict",
        "",
        "",
    ]
    for cid, cls in sem.classes.items():
        fname = cid[0].lower() + cid[1:]
        lines.append(f"class {cid}Filters(TypedDict, total=False):")
        for prop in cls.get("properties", []):
            pt = ext.property_types.get(prop)
            py = PY_TYPE.get(pt.get("value_type", "string"), "str") if pt else "Any"
            lines.append(f"    {prop}: Any  # value_type={py}")
        lines.append("")
        lines.append(f"def {fname}_query(where: {cid}Filters, extras: Optional[QueryExtras] = None) -> dict:")
        lines.append(f"    return {{'set': {{'from': '{cid}'}}, 'where': dict(where), **(extras or {{}})}}")
        lines.append("")
    for did, dt in _derived_entries(sem):
        fname = did[0].lower() + did[1:]
        name = _pascal(did)
        lines.append(f"class {name}Filters(TypedDict, total=False):")
        for prop in dt.get("properties", []):
            lines.append(f"    {prop}: Any")
        lines.append("")
        lines.append(f"def {fname}_query(where: {name}Filters, extras: Optional[QueryExtras] = None) -> dict:")
        lines.append(f"    return {{'set': {{'from': '{did}'}}, 'where': dict(where), **(extras or {{}})}}")
        lines.append("")
    lines += [
        "class OntologyClient:",
        "    def __init__(self, base_url: str, user: str = 'anonymous', roles: str = ''):",
        "        self.base = base_url.rstrip('/')",
        "        self.user = user",
        "        self.roles = roles",
        "",
        "    def _get(self, path: str, **params: Any) -> dict:",
        "        qs = '&'.join(f'{k}={v}' for k, v in params.items() if v is not None)",
        "        url = f'{self.base}{path}' + (f'?{qs}' if qs else '')",
        "        with urllib.request.urlopen(url) as r:  # noqa: S310",
        "            return json.loads(r.read())",
        "",
        "    def _post(self, path: str, body: dict) -> dict:",
        "        req = urllib.request.Request(  # noqa: S310",
        "            f'{self.base}{path}', data=json.dumps(body).encode(),",
        "            headers={'content-type': 'application/json'}, method='POST')",
        "        with urllib.request.urlopen(req) as r:  # noqa: S310",
        "            return json.loads(r.read())",
        "",
        "    def fetch_objects(self, type: str, q: str | None = None, limit: int = 20) -> dict:",
        "        return self._get('/enh/objects', type=type, q=q, limit=limit,",
        "                         user=self.user, roles=self.roles)",
        "",
        "    def call_function(self, function_id: str, args: dict) -> dict:",
        "        return self._post(f'/enh/functions/{function_id}/call', {'args': args})",
        "",
        "    def security_simulate(self, user: str, roles: list[str], class_id: str) -> dict:",
        "        return self._post('/enh/security/simulate',",
        "                          {'user': user, 'roles': roles, 'class_id': class_id})",
        "",
    ]
    return "\n".join(lines) + "\n"


def generate_openapi(sem: SemanticLayer, ext: ExtensionRegistry) -> dict:
    schemas: dict = {}
    for cid, cls in sem.classes.items():
        props_schema: dict = {
            "object_id": {"type": "string"},
            "type": {"const": cid},
            "name": {"type": "string"},
        }
        for prop in cls.get("properties", []):
            pt = ext.property_types.get(prop)
            vtype = pt.get("value_type", "string") if pt else "string"
            props_schema[prop] = {"type": vtype if vtype != "integer" else "integer"}
        schemas[cid] = {
            "type": "object",
            "properties": props_schema,
            "required": ["object_id"],
        }
    # 派生类型 schema（标注 x-derived）
    for did, dt in _derived_entries(sem):
        props_schema: dict = {
            "object_id": {"type": "string"},
            "type": {"const": did},
            "name": {"type": "string"},
        }
        for prop in dt.get("properties", []):
            pt = ext.property_types.get(prop)
            vtype = pt.get("value_type", "string") if pt else "string"
            props_schema[prop] = {"type": vtype if vtype != "integer" else "integer"}
        schemas[did] = {
            "type": "object",
            "properties": props_schema,
            "required": ["object_id"],
            "x-derived": True,
        }
    return {
        "openapi": "3.1.0",
        "info": {
            "title": "mobility-ontology OSDK-lite",
            "version": ext.meta.get("version", "1.0.0"),
            "description": "从本体 JSON 生成的类型化接口规范",
        },
        "paths": {
            "/enh/objects": {
                "get": {
                    "summary": "安全读对象列表（行级过滤+列级脱敏）",
                    "parameters": [
                        {"name": "type", "in": "query", "schema": {"type": "string"}},
                        {"name": "q", "in": "query", "schema": {"type": "string"}},
                        {"name": "user", "in": "query", "schema": {"type": "string"}},
                        {"name": "roles", "in": "query", "schema": {"type": "string"}},
                    ],
                    "responses": {"200": {"description": "OK"}},
                }
            },
            "/enh/functions/{function_id}/call": {
                "post": {
                    "summary": "调用注册表函数（scope token 检查）",
                    "parameters": [
                        {"name": "function_id", "in": "path", "required": True,
                         "schema": {"type": "string"}},
                    ],
                    "responses": {"200": {"description": "OK"}},
                }
            },
        },
        "components": {"schemas": schemas},
    }


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--out", default=os.path.join(ROOT, "generated", "osdk"))
    args = parser.parse_args()

    sem = SemanticLayer()
    ext = ExtensionRegistry(base_classes=sem.classes)
    os.makedirs(args.out, exist_ok=True)

    ts_path = os.path.join(args.out, "typescript.ts")
    py_path = os.path.join(args.out, "python_client.py")
    oa_path = os.path.join(args.out, "openapi.json")

    with open(ts_path, "w", encoding="utf-8") as f:
        f.write(generate_typescript(sem, ext))
    with open(py_path, "w", encoding="utf-8") as f:
        f.write(generate_python(sem, ext))
    with open(oa_path, "w", encoding="utf-8") as f:
        json.dump(generate_openapi(sem, ext), f, ensure_ascii=False, indent=1)

    n_classes = len(sem.classes)
    print(f"生成 {n_classes} 个类的类型化客户端:")
    print(f"  {ts_path}")
    print(f"  {py_path}")
    print(f"  {oa_path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
